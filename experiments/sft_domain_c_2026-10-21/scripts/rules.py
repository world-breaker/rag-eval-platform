def _hits(sub_list, rx_list, text: str) -> bool:
    for s in sub_list:
        if s in text:
            return True
    for p in rx_list:
        if re.search(p, text):
            return True
    return False


def compute_label(question: str) -> Dict[str, object]:
    """**唯一的标签来源**。输入一句客户问句，返回决策与编号集合。"""
    q = (question or "").strip()
    redline: List[str] = []
    transfer: List[str] = []

    if _hits(R1_SUB, R1_RX, q):
        redline.append("R1")
    if _hits(R2_SUB, R2_RX, q):
        redline.append("R2")
    if _hits(R3_SUB, R3_RX, q):
        redline.append("R3")
    if _hits(R4_SUB, R4_RX, q):
        redline.append("R4")
    if _hits(R5_SUB, R5_RX, q):
        redline.append("R5")
    if _hits(R6_DEVIATION, [], q) and _hits(R6_CONTEXT, [], q):
        redline.append("R6")

    if _hits(T1_SUB, T1_RX, q):
        transfer.append("T1")
    if _hits(T2_SUB, T2_RX, q):
        transfer.append("T2")
    if _hits(T3_SUB, T3_RX, q):
        transfer.append("T3")
    if _hits(T4_SUB, T4_RX, q):
        transfer.append("T4")
    if _hits(T5_SUB, T5_RX, q):
        transfer.append("T5")

    # ---- 优先级消歧：T3（法律/监管/暴力催收指控）优先于 T1（普通投诉/情绪激动） ----
    # 依据：probe 的人工标签 C-22「向监管部门投诉 + 上门威胁」只判 T3，不判 T1。
    if "T3" in transfer and "T1" in transfer:
        transfer.remove("T1")

    if redline:
        decision = "拒答"
    elif transfer:
        decision = "转人工"
    else:
        decision = "回答"

    return {
        "decision": decision,
        "redline": redline,
        "transfer_rules": transfer,
    }


def matched_fragments(question: str) -> List[str]:
    """返回这句问句里**命中的触发片段原文**（子串触发词 + 正则匹配文本）。

    用途：LLM 改写时把这些片段作为「必须原样保留」的约束交给模型，
    改写后再跑 `compute_label` 复核 —— 标签漂移就丢弃重采样。
    """
    q = (question or "").strip()
    frags: List[str] = []

    def collect(sub_list, rx_list):
        for s in sub_list:
            if s in q:
                frags.append(s)
        for p in rx_list:
            m = re.search(p, q)
            if m:
                frags.append(m.group(0))

    collect(R1_SUB, R1_RX)
    collect(R2_SUB, R2_RX)
    collect(R3_SUB, R3_RX)
    collect(R4_SUB, R4_RX)
    collect(R5_SUB, R5_RX)
    collect(T1_SUB, T1_RX)
    collect(T2_SUB, T2_RX)
    collect(T3_SUB, T3_RX)
    collect(T4_SUB, T4_RX)
    collect(T5_SUB, T5_RX)
    for d in R6_DEVIATION:
        if d in q:
            frags.append(d)
    # 去重但保持顺序
    seen, out = set(), []
    for f in frags:
        if f not in seen:
            seen.add(f)
            out.append(f)
    return out


